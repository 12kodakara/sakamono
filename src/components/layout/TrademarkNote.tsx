/**
 * 「ここは公式サイトではありません」を伝える1行。
 *
 * ══════════════════════════════════════════════════════════
 * ★なぜページの中にも出すのか★
 *
 *   フッターには全ページ共通の商標・非提携の表記があります。
 *   ただし商品ページには「○○公式ストアで探す」ボタンがあり、
 *   クラブ名と商品名が並ぶため、公式サイトや公式の取扱店だと
 *   受け取られやすい場所です。フッターまで読まない人にも届くよう、
 *   本文の最後に1行だけ置きます。
 *
 * ★大きく出さない・重ねて出さない★
 *   注意書きを大きくしても読まれません。小さな文字で1回だけにします。
 *   クラブページは以前から同じ趣旨の1行を出しているので、
 *   この部品に寄せて文言を1か所で管理します。
 * ══════════════════════════════════════════════════════════
 */

export interface TrademarkNoteProps {
  /**
   * 名前を挙げる相手（クラブ名など）。
   * 渡すと「○○の名称・エンブレムは…」の形になります。
   * 省略すると、相手を特定しない一般的な言い方になります。
   */
  ownerNameJa?: string
}

export function TrademarkNote({ ownerNameJa }: TrademarkNoteProps) {
  return (
    <p style={{ fontSize: 'var(--text-sm)', color: 'var(--color-text-muted)' }}>
      {ownerNameJa ? `${ownerNameJa}の名称・エンブレムは同クラブの商標です。` : null}
      サカモノは各クラブ・メーカー・販売店の公式サイトではなく、提携・運営関係もありません。
    </p>
  )
}
