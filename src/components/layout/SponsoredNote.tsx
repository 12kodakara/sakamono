/**
 * 「このページには広告（アフィリエイト）リンクがあります」を伝える表示。
 *
 * ══════════════════════════════════════════════════════════
 * ★広告リンクが実際にあるページだけに出します。★
 *
 *   提携していないうちに「広告を含みます」と書くと、事実と違う表示になります。
 *   逆に提携してから書き忘れると、広告だと分からないまま押させることになります。
 *   どちらも避けるため、表示するかどうかは広告リンクの有無で決めます
 *   （src/lib/purchaseLink.ts の isSponsored）。
 *
 *   いまは提携しているストアが1つも無いため、このコンポーネントは
 *   どのページにも描画されません。提携が決まり、データ側で
 *   affiliateAvailable が true になった時点で自動的に出ます。
 *
 * ★リンクのすぐ近くに置きます。★
 *   ページの隅や、スクロールしないと見えない場所にあると、
 *   押す人が広告だと気づけません。ボタンの直前に置きます。
 *
 * ★断定的な宣伝文は書きません。★
 *   「最安」「今だけ」などは実データで裏づけられないため使いません。
 * ══════════════════════════════════════════════════════════
 */

export interface SponsoredNoteProps {
  /**
   * このページに広告（アフィリエイト）リンクがあるか。
   * false のときは何も描画しません（不要な表示を出さないため）。
   */
  hasSponsoredLink: boolean
}

export function SponsoredNote({ hasSponsoredLink }: SponsoredNoteProps) {
  if (!hasSponsoredLink) return null

  return (
    <p className="sponsored-note" role="note">
      <strong>広告</strong>
      このページには広告（アフィリエイト）リンクが含まれます。
      リンクから購入された場合、サカモノに紹介料が支払われることがあります。
      掲載内容や価格の表示が、紹介料の有無によって変わることはありません。
    </p>
  )
}
